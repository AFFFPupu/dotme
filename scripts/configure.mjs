#!/usr/bin/env node
// Writes wrangler.deploy.jsonc: the template wrangler.jsonc plus this install's
// own values from dotme.config.json. Both output and input are gitignored, so
// the repo stays a template that anyone can deploy for themselves.
//
//   node scripts/configure.mjs           write wrangler.deploy.jsonc
//   node scripts/configure.mjs --check   validate dotme.config.json only

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const configPath = join(root, "dotme.config.json");
const templatePath = join(root, "wrangler.jsonc");
const outputPath = join(root, "wrangler.deploy.jsonc");

const fail = (message) => {
  console.error(`configure: ${message}`);
  process.exit(1);
};

// JSON with comments and trailing commas, as wrangler.jsonc allows.
export function parseJsonc(text) {
  let out = "";
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      let j = i + 1;
      while (j < text.length && text[j] !== '"') j += text[j] === "\\" ? 2 : 1;
      out += text.slice(i, j + 1);
      i = j;
    } else if (c === "/" && text[i + 1] === "/") {
      while (i < text.length && text[i] !== "\n") i++;
      out += "\n";
    } else if (c === "/" && text[i + 1] === "*") {
      i = text.indexOf("*/", i + 2);
      if (i < 0) throw new Error("unterminated comment");
      i++;
    } else {
      out += c;
    }
  }
  // Drop trailing commas, again skipping strings.
  return JSON.parse(out.replace(/("(?:[^"\\]|\\.)*")|,(\s*[}\]])/g, (m, str, close) => str ?? close));
}

export function validate(config) {
  const errors = [];
  const { workerName, url, kvNamespaceId, githubRepo } = config ?? {};
  if (typeof workerName !== "string" || !/^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/.test(workerName))
    errors.push('workerName: lowercase letters, digits and dashes, for example "dotme"');
  let origin;
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== "https:" || parsed.pathname !== "/" || parsed.search || parsed.hash) throw new Error();
    if (parsed.hostname.endsWith(".example.workers.dev")) throw new Error();
    origin = parsed.origin;
  } catch {
    errors.push('url: the Worker\'s https origin with no path, for example "https://dotme.<your-subdomain>.workers.dev"');
  }
  if (typeof kvNamespaceId !== "string" || !/^[0-9a-f]{32}$/.test(kvNamespaceId) || /^0+$/.test(kvNamespaceId))
    errors.push("kvNamespaceId: the 32-character id printed by `npx wrangler kv namespace create OAUTH_KV`");
  if (typeof githubRepo !== "string" || !/^[\w.-]+\/[\w.-]+$/.test(githubRepo) || githubRepo.startsWith("your-github-login/"))
    errors.push('githubRepo: your private data repo as "owner/name"');
  return { errors, origin };
}

function main() {
  if (!existsSync(configPath))
    fail("dotme.config.json not found. Copy dotme.config.example.json to dotme.config.json and fill it in.");
  let config;
  try {
    config = JSON.parse(readFileSync(configPath, "utf8"));
  } catch (e) {
    fail(`dotme.config.json is not valid JSON: ${e.message}`);
  }
  const { errors, origin } = validate(config);
  if (errors.length) fail(`dotme.config.json needs fixing:\n  ${errors.join("\n  ")}`);
  if (process.argv.includes("--check")) {
    console.log("configure: dotme.config.json is valid");
    return;
  }

  const wrangler = parseJsonc(readFileSync(templatePath, "utf8"));
  wrangler.name = config.workerName;
  wrangler.vars = { ...wrangler.vars, MCP_RESOURCE: `${origin}/mcp`, GITHUB_REPO: config.githubRepo };
  const kv = wrangler.kv_namespaces?.find((n) => n.binding === "OAUTH_KV");
  if (!kv) fail("wrangler.jsonc has no OAUTH_KV namespace");
  kv.id = config.kvNamespaceId;

  const header = "// Generated by scripts/configure.mjs from wrangler.jsonc and dotme.config.json. Do not edit;\n// change those files and run `npm run configure` again.\n";
  writeFileSync(outputPath, header + JSON.stringify(wrangler, null, 2) + "\n");
  console.log(`configure: wrote wrangler.deploy.jsonc for ${config.workerName} at ${origin}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
