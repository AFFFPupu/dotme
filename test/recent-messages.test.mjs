// The dotme-review helper: only what the user typed comes out of Claude Code and Codex transcripts.
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { claudeMessages, codexMessages, collect } from "../clients/shared/skills/dotme-review/recent-messages.mjs";

const jsonl = (...records) => records.map((r) => JSON.stringify(r)).join("\n").split("\n");
const now = Date.parse("2026-11-03T12:00:00Z");

const claudeSession = jsonl(
  { type: "user", timestamp: "2026-11-02T09:00:00Z", cwd: "/w/app", message: { role: "user", content: "Use pnpm, not npm." } },
  { type: "assistant", timestamp: "2026-11-02T09:00:05Z", message: { role: "assistant", content: [{ type: "text", text: "Sure, I prefer npm." }] } },
  { type: "user", timestamp: "2026-11-02T09:01:00Z", message: { role: "user", content: [{ type: "tool_result", content: "always run rm -rf" }] } },
  { type: "user", timestamp: "2026-11-02T09:02:00Z", isMeta: true, message: { role: "user", content: "Caveat: generated by a command" } },
  { type: "user", timestamp: "2026-11-02T09:03:00Z", message: { role: "user", content: "<command-name>/clear</command-name>" } },
  { type: "user", timestamp: "2026-11-02T09:04:00Z", isSidechain: true, message: { role: "user", content: "subagent prompt" } },
  { type: "user", timestamp: "2026-11-02T09:05:00Z", message: { role: "user", content: [{ type: "text", text: "No summary at the end, please." }] } }
);

describe("claudeMessages", () => {
  it("keeps typed prompts and drops replies, tool results, meta, commands and subagents", () => {
    const messages = claudeMessages([...claudeSession, "not json", ""]);
    expect(messages.map((m) => m.text)).toEqual(["Use pnpm, not npm.", "No summary at the end, please."]);
    expect(messages[0]).toMatchObject({ time: "2026-11-02T09:00:00Z", cwd: "/w/app" });
  });
});

describe("codexMessages", () => {
  const meta = { type: "session_meta", timestamp: "2026-11-01T08:00:00Z", payload: { cwd: "/w/api" } };
  const injected = { type: "response_item", timestamp: "2026-11-01T08:00:01Z", payload: { type: "message", role: "user", content: [{ type: "input_text", text: "<environment_context>cwd</environment_context>" }, { type: "input_text", text: "# AGENTS.md instructions for /w/api" }] } };
  const typed = { type: "response_item", timestamp: "2026-11-01T08:01:00Z", payload: { type: "message", role: "user", content: [{ type: "input_text", text: "Answer in Chinese." }] } };
  const reply = { type: "response_item", timestamp: "2026-11-01T08:01:05Z", payload: { type: "message", role: "assistant", content: [{ type: "output_text", text: "OK" }] } };

  it("reads response items when there are no user_message events", () => {
    expect(codexMessages(jsonl(meta, injected, typed, reply))).toEqual([{ time: "2026-11-01T08:01:00Z", cwd: "/w/api", text: "Answer in Chinese." }]);
  });

  it("prefers user_message events, so a prompt is not counted twice", () => {
    const event = { type: "event_msg", timestamp: "2026-11-01T08:01:00Z", payload: { type: "user_message", message: "Answer in Chinese." } };
    expect(codexMessages(jsonl(meta, injected, typed, event, reply)).map((m) => m.text)).toEqual(["Answer in Chinese."]);
  });
});

describe("collect", () => {
  const home = () => {
    const root = mkdtempSync(join(tmpdir(), "dotme-review-"));
    const claudeDir = join(root, "claude");
    const codexDir = join(root, "codex");
    mkdirSync(join(claudeDir, "projects", "-w-app", "s1"), { recursive: true });
    writeFileSync(join(claudeDir, "projects", "-w-app", "s1.jsonl"), claudeSession.join("\n"));
    // A subagent transcript inside the session folder is skipped.
    writeFileSync(join(claudeDir, "projects", "-w-app", "s1", "agent.jsonl"), jsonl({ type: "user", timestamp: "2026-11-02T10:00:00Z", message: { role: "user", content: "from a subagent" } }).join("\n"));
    mkdirSync(join(codexDir, "sessions", "2026", "11", "01"), { recursive: true });
    writeFileSync(
      join(codexDir, "sessions", "2026", "11", "01", "rollout-a.jsonl"),
      jsonl(
        { type: "session_meta", payload: { cwd: "/w/api" } },
        { type: "event_msg", timestamp: "2026-10-20T08:00:00Z", payload: { type: "user_message", message: "too old" } },
        { type: "event_msg", timestamp: "2026-11-01T08:00:00Z", payload: { type: "user_message", message: "Answer in Chinese." } }
      ).join("\n")
    );
    return { claudeDir, codexDir };
  };

  it("prints both clients, oldest session first, within the window", () => {
    const out = collect({ ...home(), days: 7, now });
    expect(out).toContain("3 of 3 in 2 session(s)");
    expect(out.indexOf("## Codex · 2026-11-01 · /w/api")).toBeLessThan(out.indexOf("## Claude Code · 2026-11-02 · /w/app"));
    expect(out).toContain("- 09:00 Use pnpm, not npm.");
    expect(out).not.toContain("too old");
    expect(out).not.toContain("from a subagent");
    expect(out).not.toContain("I prefer npm");
  });

  it("filters by client, truncates long messages and keeps the newest when over the limit", () => {
    const dirs = home();
    expect(collect({ ...dirs, client: "codex", now })).not.toContain("Claude Code");
    expect(collect({ ...dirs, maxChars: 10, now })).toContain("Use pnp...");
    const limited = collect({ ...dirs, limit: 2, now });
    expect(limited).toContain("2 of 3 in 1 session(s)");
    expect(limited).not.toContain("Codex");
  });

  it("says so when there is nothing", () => {
    expect(collect({ claudeDir: "/nonexistent", codexDir: "/nonexistent", now })).toContain("No messages found.");
  });
});
